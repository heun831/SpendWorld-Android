const header = document.querySelector("[data-header]");
const nav = document.querySelector("[data-nav]");
const menuToggle = document.querySelector("[data-menu-toggle]");
const year = document.querySelector("[data-year]");
const form = document.querySelector("[data-waitlist]");
const statusEl = document.querySelector("[data-status]");

if (year) year.textContent = String(new Date().getFullYear());

const applyLang = (lang) => {
  const dict = copy[lang] || copy.ko;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (dict[key]) node.textContent = dict[key];
  });
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });
  localStorage.setItem("spendworld-lang", lang);
};

const savedLang = localStorage.getItem("spendworld-lang") || "ko";
applyLang(savedLang);

document.querySelectorAll("[data-lang]").forEach((btn) => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});

window.addEventListener("scroll", () => {
  header?.classList.toggle("is-scrolled", window.scrollY > 8);
}, { passive: true });

menuToggle?.addEventListener("click", () => {
  const open = nav.classList.toggle("is-open");
  menuToggle.setAttribute("aria-expanded", String(open));
});

nav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    nav.classList.remove("is-open");
    menuToggle?.setAttribute("aria-expanded", "false");
  });
});

form?.addEventListener("submit", (event) => {
  event.preventDefault();
  const email = new FormData(form).get("email");
  const lang = document.documentElement.lang || "ko";
  const list = JSON.parse(localStorage.getItem("spendworld-waitlist") || "[]");
  if (email && !list.includes(email)) list.push(email);
  localStorage.setItem("spendworld-waitlist", JSON.stringify(list));
  if (statusEl) {
    statusEl.hidden = false;
    statusEl.dataset.state = "ok";
    statusEl.textContent = copy[lang]["cta.ok"];
  }
  form.reset();
});
